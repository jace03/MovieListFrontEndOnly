-- Replaces the earlier uuid-based schema with the MySQL 'movieslist' shape (holidays, ranks, watch
-- windows). Data was loaded afterwards from supabase/movielist_dump.sql, skipping the movie_actor rows
-- that point at a movie or actor missing from the dump.
drop table if exists public.movie_actor;
drop table if exists public.movies;
drop table if exists public.actors;

create table public.holidays (
  id bigint generated by default as identity primary key,
  name text not null unique,
  emoji text not null default '?',
  sort_order integer not null default 0,
  day_of_count smallint not null default 3,
  week_of_count smallint not null default 7,
  two_weeks_away_count smallint not null default 4,
  three_weeks_away_count smallint not null default 4,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.actors (
  id bigint generated by default as identity primary key,
  name text not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.movies (
  id bigint generated by default as identity primary key,
  title text not null,
  year smallint,
  added_by text not null default 'Both' check (added_by in ('His','Hers','Both')),
  genre text,
  decade text,
  holiday_id bigint references public.holidays(id) on delete set null,
  rank integer not null default 100,
  watch_window text not null default 'month_away'
    check (watch_window in ('day_of','week_of','two_weeks_away','three_weeks_away','month_away')),
  watched boolean not null default false,
  notes text not null default '',
  poster_url text,
  rating integer not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index movies_holiday_id_idx on public.movies(holiday_id);

create table public.movie_actor (
  id bigint generated by default as identity primary key,
  movie_id bigint not null references public.movies(id) on delete cascade,
  actor_id bigint not null references public.actors(id) on delete cascade,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index movie_actor_movie_id_idx on public.movie_actor(movie_id);
create index movie_actor_actor_id_idx on public.movie_actor(actor_id);

-- No auth in this app: anyone with the publishable key can read/write (accepted tradeoff, hobby data).
alter table public.holidays enable row level security;
alter table public.actors enable row level security;
alter table public.movies enable row level security;
alter table public.movie_actor enable row level security;
create policy "public read/write (no auth in this app)" on public.holidays for all to anon, authenticated using (true) with check (true);
create policy "public read/write (no auth in this app)" on public.actors for all to anon, authenticated using (true) with check (true);
create policy "public read/write (no auth in this app)" on public.movies for all to anon, authenticated using (true) with check (true);
create policy "public read/write (no auth in this app)" on public.movie_actor for all to anon, authenticated using (true) with check (true);

create function public.touch_updated_at() returns trigger
language plpgsql set search_path = '' as $$
begin
  new.updated_at := now();
  return new;
end $$;
create trigger holidays_touch before update on public.holidays for each row execute function public.touch_updated_at();
create trigger movies_touch before update on public.movies for each row execute function public.touch_updated_at();

-- Fills a holiday's calendar from its ranking: the top day_of_count movies go to 'day_of', the next
-- week_of_count to 'week_of', and so on; everything else goes to 'month_away'.
create function public.auto_calculate_calendar(p_holiday_id bigint) returns setof public.movies
language sql set search_path = '' as $$
  with h as (
    select day_of_count d, week_of_count w, two_weeks_away_count t2, three_weeks_away_count t3
    from public.holidays where id = p_holiday_id
  ), ordered as (
    select m.id, row_number() over (order by m.rank, m.title, m.id) as pos
    from public.movies m where m.holiday_id = p_holiday_id
  )
  update public.movies m set watch_window = case
      when o.pos <= h.d then 'day_of'
      when o.pos <= h.d + h.w then 'week_of'
      when o.pos <= h.d + h.w + h.t2 then 'two_weeks_away'
      when o.pos <= h.d + h.w + h.t2 + h.t3 then 'three_weeks_away'
      else 'month_away' end
  from ordered o, h
  where m.id = o.id
  returning m.*;
$$;

-- Puts every movie of a holiday back in 'month_away'. Never deletes a movie.
create function public.clear_calendar(p_holiday_id bigint) returns setof public.movies
language sql set search_path = '' as $$
  update public.movies set watch_window = 'month_away'
  where holiday_id = p_holiday_id
  returning *;
$$;
